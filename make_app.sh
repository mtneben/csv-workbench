#!/bin/bash
# Build csvcsvworkbench.app — a double-clickable macOS app for this checkout.
#
#   ./make_app.sh              -> ~/Applications/csvcsvworkbench.app
#   ./make_app.sh /Applications -> /Applications/csvcsvworkbench.app
#
# The bundle is a shell script plus an Info.plist and the .icns from gen_icon.py.
# No Automator, no signing, no Terminal window.

set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEST="${1:-$HOME/Applications}"
APP="$DEST/csvcsvworkbench.app"
PY="${WORKBENCH_PYTHON:-$HERE/bin/python}"
PORT="${WORKBENCH_PORT:-8840}"

[ -x "$PY" ] || PY="$HOME/venvs/csvworkbench/bin/python"
if [ ! -x "$PY" ]; then
  echo "No python found. Set WORKBENCH_PYTHON=/path/to/venv/bin/python" >&2
  exit 1
fi
if [ ! -f "$HERE/static/AppIcon.icns" ]; then
  echo "static/AppIcon.icns missing — run: python3 gen_icon.py" >&2
  exit 1
fi

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>csvcsvworkbench</string>
  <key>CFBundleDisplayName</key><string>csvworkbench</string>
  <key>CFBundleIdentifier</key><string>com.mtneben.csvworkbench</string>
  <key>CFBundleExecutable</key><string>csvcsvworkbench</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
</dict>
</plist>
PLIST

cp "$HERE/static/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"

cat > "$APP/Contents/MacOS/csvcsvworkbench" <<LAUNCHER
#!/bin/bash
# Generated by make_app.sh — re-run it if the project moves.
APP_DIR="$HERE"
PY="$PY"
PORT="$PORT"
URL="http://127.0.0.1:\$PORT/"
LOG="\$HOME/Library/Logs/csvworkbench.log"
mkdir -p "\$(dirname "\$LOG")"

cd "\$APP_DIR" || exit 1

# log every attempt, including the no-op path: a launcher that fails silently
# is impossible to diagnose from the outside
echo "--- \$(date) launch requested" >> "\$LOG"

# already running? just show it
if /usr/bin/curl -s -o /dev/null --max-time 1 "\$URL"; then
  echo "    a server is already listening on \$URL — opening the browser" >> "\$LOG"
  /usr/bin/open "\$URL"
  exit 0
fi

echo "    starting \$PY server.py \$PORT" >> "\$LOG"
"\$PY" server.py "\$PORT" 127.0.0.1 >> "\$LOG" 2>&1 &
SERVER_PID=\$!
trap 'kill \$SERVER_PID 2>/dev/null' TERM INT EXIT

for _ in \$(seq 1 60); do
  sleep 0.25
  if /usr/bin/curl -s -o /dev/null --max-time 1 "\$URL"; then break; fi
done

if ! /usr/bin/curl -s -o /dev/null --max-time 1 "\$URL"; then
  /usr/bin/osascript -e 'display dialog "csvworkbench did not start. See ~/Library/Logs/csvworkbench.log" buttons {"OK"} default button 1 with title "csvworkbench"' >/dev/null 2>&1
  exit 1
fi

/usr/bin/open "\$URL"

# stay alive while the server runs, so quitting the app stops it
wait \$SERVER_PID
LAUNCHER

chmod +x "$APP/Contents/MacOS/csvcsvworkbench"
/usr/bin/xattr -dr com.apple.quarantine "$APP" 2>/dev/null || true

echo "built: $APP"
echo "  python: $PY"
echo "  port:   $PORT"
echo "Drag it to the Dock, or: open \"$APP\""
